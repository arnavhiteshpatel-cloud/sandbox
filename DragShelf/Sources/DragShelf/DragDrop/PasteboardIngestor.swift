import AppKit
import UniformTypeIdentifiers
import DragShelfCore

/// Helpers for pasteboard flavours.
enum DataFlavors {
    static let urlName = NSPasteboard.PasteboardType("public.url-name")
    static let imageTypes: [String] = ["public.png", "public.jpeg", "public.heic", "public.tiff", "com.compuserve.gif",
                                       "public.webp", "org.webmproject.webp", "com.microsoft.bmp", "public.image"]

    /// Flavours that describe file promises or the drag itself rather than content; never stored.
    static let skippedTypes: Set<String> = [
        "com.apple.NSFilePromiseItemMetaData", "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-content-type", "com.apple.pasteboard.promised-file-name",
        "com.apple.pasteboard.promised-suggested-file-name",
        "NSPromiseContentsPboardType", "Apple files promise pasteboard type", "NSFilenamesPboardType",
        "com.apple.finder.node", "com.apple.pasteboard.NSFilePromiseID",
        "org.nspasteboard.source", "dyn.ah62d4rv4gu8yc6durvwwaznwmuuha2pxsvw0e55bsmwca7d3sbwu",
    ]

    /// Clipboard managers' conventions for content that must not be recorded.
    static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "com.apple.is-remote-clipboard",
    ]

    /// Per-representation cap, so a huge flavour can't exhaust memory or disk.
    static let maxRepresentationBytes = 256 * 1024 * 1024

    static func isImageType(_ t: String) -> Bool {
        if imageTypes.contains(t) { return true }
        return UTType(t)?.conforms(to: .image) ?? false
    }

    /// A stored representation QuickLook can render (images, PDFs), preferring compressed formats.
    static func previewRepresentation(_ d: DataItem) -> DataRepresentation? {
        for t in ["public.png", "public.jpeg", "public.heic", "com.compuserve.gif", "public.tiff", "com.adobe.pdf"] {
            if let r = d.representation(ofType: t) { return r }
        }
        return d.representations.first { isImageType($0.type) }
    }

    static func fileExtension(for type: String) -> String? {
        UTType(type)?.preferredFilenameExtension
    }
}

/// Turns pasteboard contents (a drop, or the general clipboard) into shelf items.
///
/// Order of preference:
///   1. File URLs → references to the originals (nothing is copied).
///   2. File promises (screenshots' floating thumbnail, Photos, Mail attachments, browser
///      images) → received into DragShelf's own storage.
///   3. Everything else → every flavour stored verbatim, so dragging out re-offers the same types.
final class PasteboardIngestor {
    let store: ShelfStore
    private let promiseQueue: OperationQueue = {
        let q = OperationQueue()
        q.name = "DragShelf.promises"
        q.qualityOfService = .userInitiated
        return q
    }()

    init(store: ShelfStore) {
        self.store = store
    }

    struct Result {
        var items: [ShelfItem]
        /// Promised files still being written; delivered later through `completion`.
        var pendingPromises: Int
    }

    /// Reads `pasteboard` synchronously (it is only valid during the drop) and returns the items
    /// available immediately. Items from file promises arrive later via `promised`.
    func ingest(_ pasteboard: NSPasteboard, allowPromises: Bool = true,
                promised: @escaping ([ShelfItem]) -> Void) -> Result {
        // 1. Files
        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self],
                                               options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !fileURLs.isEmpty {
            return Result(items: fileURLs.map(makeFileItem), pendingPromises: 0)
        }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let hasWebURL = webURL(from: pasteboard) != nil
        let hasImage = types.contains(where: DataFlavors.isImageType)

        // 2. Promises (but a plain link drag that also promises a .webloc stays a link)
        if allowPromises, !(hasWebURL && !hasImage),
           let receivers = pasteboard.readObjects(forClasses: [NSFilePromiseReceiver.self], options: nil) as? [NSFilePromiseReceiver],
           !receivers.isEmpty {
            let count = receive(receivers, completion: promised)
            if count > 0 { return Result(items: [], pendingPromises: count) }
        }

        // 3. Raw flavours
        let items = (pasteboard.pasteboardItems ?? []).compactMap(makeDataItem)
        return Result(items: items, pendingPromises: 0)
    }

    // MARK: Files

    func makeFileItem(_ url: URL) -> ShelfItem {
        let ref = FileResolver.makeReference(for: url)
        let (kind, uti) = FileResolver.kind(for: url)
        let name = (try? url.resourceValues(forKeys: [.localizedNameKey]))?.localizedName ?? url.lastPathComponent
        return ShelfItem(content: .file(ref), kind: kind, displayName: name, typeIdentifier: uti)
    }

    // MARK: Promises

    /// Thread-safe bookkeeping for one drop's promises (callbacks arrive on a background queue).
    private final class PromiseCollector: @unchecked Sendable {
        let lock = NSLock()
        let group = DispatchGroup()
        var received: [(Int, ShelfItem)] = []
        var remaining: [Int: Int] = [:]
        var finished: Set<Int> = []

        func start(_ index: Int, expected: Int) {
            lock.lock(); remaining[index] = expected; lock.unlock()
            group.enter()
        }

        func deliver(_ index: Int, item: ShelfItem?) {
            lock.lock()
            if let item = item { received.append((index, item)) }
            remaining[index, default: 1] -= 1
            let done = (remaining[index] ?? 0) <= 0
            lock.unlock()
            if done { finish(index) }
        }

        func finish(_ index: Int) {
            lock.lock()
            let first = finished.insert(index).inserted
            lock.unlock()
            if first { group.leave() }
        }

        func items() -> [ShelfItem] {
            lock.lock(); defer { lock.unlock() }
            return received.sorted { $0.0 < $1.0 }.map { $0.1 }
        }
    }

    /// Starts receiving promised files. Returns the number of receivers started.
    private func receive(_ receivers: [NSFilePromiseReceiver], completion: @escaping ([ShelfItem]) -> Void) -> Int {
        let collector = PromiseCollector()
        let store = self.store
        var started = 0

        for (index, receiver) in receivers.enumerated() {
            guard let dir = try? store.makeBlobDirectory() else { continue }
            started += 1
            collector.start(index, expected: max(1, receiver.fileNames.count))
            let blobName = dir.name
            receiver.receivePromisedFiles(atDestination: dir.url, options: [:], operationQueue: promiseQueue) { url, error in
                let item = error == nil ? PasteboardIngestor.makeStoredFileItem(url, blobDirectory: blobName, store: store) : nil
                collector.deliver(index, item: item)
            }
            // Some sources report fewer callbacks than file names; don't wait forever.
            DispatchQueue.global().asyncAfter(deadline: .now() + 120) {
                collector.finish(index)
            }
        }
        guard started > 0 else { return 0 }
        collector.group.notify(queue: .main) {
            completion(collector.items())
        }
        return started
    }

    static func makeStoredFileItem(_ url: URL, blobDirectory: String, store: ShelfStore) -> ShelfItem? {
        let fm = FileManager.default
        guard fm.fileExists(atPath: url.path) else { return nil }
        // The promise may have written into a sub-folder; record the path relative to blobs/.
        let blobs = store.blobsURL.standardizedFileURL.path + "/"
        let full = url.standardizedFileURL.path
        guard full.hasPrefix(blobs) else { return nil }
        let relative = String(full.dropFirst(blobs.count))
        guard store.blobURL(relative) != nil, relative.hasPrefix(blobDirectory + "/") else { return nil }
        let (kind, uti) = FileResolver.kind(for: url)
        let isDir = (try? url.resourceValues(forKeys: [.isDirectoryKey]))?.isDirectory ?? false
        let bytes = isDir ? ShelfStore.directorySize(url) : Int64((try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize ?? 0)
        return ShelfItem(content: .storedFile(StoredFile(relativePath: relative, originalName: url.lastPathComponent)),
                         kind: kind, displayName: url.lastPathComponent, typeIdentifier: uti, storedBytes: bytes)
    }

    // MARK: Data flavours

    func webURL(from pasteboard: NSPasteboard) -> URL? {
        for item in pasteboard.pasteboardItems ?? [] {
            if let u = webURL(from: item) { return u }
        }
        return nil
    }

    private func webURL(from item: NSPasteboardItem) -> URL? {
        if let s = item.string(forType: .URL), let u = URL(string: s), let scheme = u.scheme?.lowercased(),
           ["http", "https", "mailto", "ftp"].contains(scheme) {
            return u
        }
        return nil
    }

    func makeDataItem(_ pbItem: NSPasteboardItem) -> ShelfItem? {
        let types = pbItem.types.map(\.rawValue)
        if types.contains(where: { DataFlavors.privateMarkers.contains($0) }) { return nil }
        guard let dir = try? store.makeBlobDirectory() else { return nil }

        var reps: [DataRepresentation] = []
        var total: Int64 = 0
        for (i, type) in types.enumerated() where !DataFlavors.skippedTypes.contains(type) && !type.hasPrefix("dyn.") {
            guard let data = pbItem.data(forType: NSPasteboard.PasteboardType(type)),
                  !data.isEmpty, data.count <= DataFlavors.maxRepresentationBytes else { continue }
            var name = "rep\(i)"
            if let ext = DataFlavors.fileExtension(for: type) { name += "." + ext }
            do {
                try data.write(to: dir.url.appendingPathComponent(name), options: .atomic)
                reps.append(DataRepresentation(type: type, blob: dir.name + "/" + name, byteCount: Int64(data.count)))
                total += Int64(data.count)
            } catch { continue }
        }
        guard !reps.isEmpty else {
            store.deleteBlobDirectory(dir.name)
            return nil
        }

        let text = pbItem.string(forType: .string) ?? plainText(fromRTF: pbItem.data(forType: .rtf))
        let title = pbItem.string(forType: DataFlavors.urlName)
        var url = webURL(from: pbItem)
        if url == nil, let t = text, let detected = TextAnalysis.link(in: t) { url = detected }
        let imageRep = reps.first { DataFlavors.isImageType($0.type) }

        let kind: ItemKind
        let name: String
        let uti: String?
        if let u = url, imageRep == nil {
            kind = .link
            name = (title?.isEmpty == false) ? title! : TextAnalysis.displayHost(u)
            uti = UTType.url.identifier
        } else if let img = imageRep {
            kind = .image
            name = title ?? url.map { $0.lastPathComponent.isEmpty ? "Image" : $0.lastPathComponent } ?? "Image"
            uti = img.type
        } else if let t = text, !t.isEmpty {
            kind = .text
            name = TextAnalysis.title(forText: t)
            uti = UTType.plainText.identifier
        } else if let pdf = reps.first(where: { $0.type == UTType.pdf.identifier }) {
            kind = .pdf
            name = "PDF"
            uti = pdf.type
        } else {
            kind = .richData
            name = UTType(reps[0].type)?.localizedDescription ?? "Data"
            uti = reps[0].type
        }

        let dataItem = DataItem(representations: reps, text: text, url: url?.absoluteString, title: title)
        return ShelfItem(content: .data(dataItem), kind: kind, displayName: name, typeIdentifier: uti, storedBytes: total)
    }

    private func plainText(fromRTF data: Data?) -> String? {
        guard let data = data,
              let s = NSAttributedString(rtf: data, documentAttributes: nil) else { return nil }
        return s.string
    }

    /// Creates a plain text item (used by the text editor and by clipboard capture of strings).
    func makeTextItem(_ text: String) -> ShelfItem? {
        let pb = NSPasteboardItem()
        pb.setString(text, forType: .string)
        return makeDataItem(pb)
    }
}
