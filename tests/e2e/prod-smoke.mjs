// Smoke test of the production bundle: scrambles (workers + WASM), 3D cube, a keyboard solve, offline.
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
const require = createRequire(execSync("npm root -g").toString().trim() + "/");
const { chromium } = require("playwright");
const URL = process.argv[2] || "http://127.0.0.1:4173";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1512, height: 945 } });
const ext = [];
await ctx.route("**/*", (r) => (r.request().url().startsWith(URL) || /^(data|blob):/.test(r.request().url()) ? r.continue() : (ext.push(r.request().url()), r.abort())));
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(URL);
await p.waitForSelector('[data-testid="app"]');
await p.waitForFunction(() => (document.querySelector('[data-testid="scramble"]')?.textContent || "").trim().split(/\s+/).length >= 15, null, { timeout: 60000 });
await p.waitForSelector("twisty-player", { timeout: 20000 });
await p.keyboard.down("Space"); await p.keyboard.up("Space");
await p.waitForTimeout(300);
await p.keyboard.down("Space"); await p.waitForTimeout(400); await p.keyboard.up("Space");
await p.waitForTimeout(900);
await p.keyboard.press("KeyK");
await p.waitForTimeout(500);
const t = (await p.textContent('[data-testid="timer"]')).trim();
await p.waitForTimeout(1500);
await p.screenshot({ path: "artifacts/shots/prod-smoke.png" });
console.log(JSON.stringify({ timer: t, external: ext.length, errors: errs }));
await b.close();
process.exit(errs.length || ext.length || !/^0\.9|^1\.\d/.test(t) ? 1 : 0);
